#!/usr/bin/env python3
"""Author the evaluation dataset.

Committed for transparency: it shows exactly how every case and every gold label came to
exist. Two properties matter, and both are structural rather than promised:

  1. **This script does not import or run the system.** There is no `import kivi` below and
     no database access. Gold labels therefore cannot have been copied from the system's
     own output — they are written here by hand, from what the product *should* do. If the
     system disagrees with a label, the evaluation reports a failure, which is the point.

  2. **Every case is a sentence someone might actually dictate.** Where a memory is tested
     in several different sentences, that is not padding: the context gate is the mechanism
     under test, so the same word in a shipping context, a fruit context and a quoted
     context are three genuinely different tests. No case is generated by permuting
     template slots to inflate a count.

Run: `python eval/build_dataset.py` (writes dev.jsonl and holdout.jsonl).
"""

from __future__ import annotations

import json
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent / "datasets"

CASES: list[dict] = []


def apply_case(
    cid: str,
    category: str,
    formatted: str,
    expected: str | None,
    note: str,
    *,
    scenario: str = "seeded",
    app: str | None = None,
    asr: str | None = None,
    reasons: list[str] | None = None,
) -> None:
    """One application case. `expected=None` means the text must come back untouched."""
    case = {
        "id": cid,
        "kind": "apply",
        "category": category,
        "scenario": scenario,
        "formatted_text": formatted,
        "expected": {
            "intervention": "none" if expected is None else "correct",
            "text": formatted if expected is None else expected,
        },
        "note": note,
    }
    if app:
        case["app_context"] = app
    if asr:
        case["asr_text"] = asr
    if reasons:
        case["expected"]["reason_contains"] = reasons
    CASES.append(case)


def learn_case(
    cid: str, category: str, observations: list[dict], memories: list[dict], note: str,
    *, scenario: str = "empty",
) -> None:
    CASES.append(
        {
            "id": cid, "kind": "learn", "category": category, "scenario": scenario,
            "observations": observations,
            "expected": {"memories": memories},
            "note": note,
        }
    )


def state_case(
    cid: str, category: str, assertions: list[dict], note: str, *, scenario: str
) -> None:
    CASES.append(
        {
            "id": cid, "kind": "state", "category": category, "scenario": scenario,
            "assertions": assertions, "note": note,
        }
    )


def obs(formatted=None, asr=None, edited=None, app=None) -> dict:
    out = {}
    if asr:
        out["asr_text"] = asr
    if formatted:
        out["formatted_text"] = formatted
    if edited:
        out["user_edited_text"] = edited
    if app:
        out["app_context"] = app
    return out



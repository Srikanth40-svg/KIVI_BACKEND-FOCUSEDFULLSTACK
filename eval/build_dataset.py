def write(path: Path, cases: list[dict]) -> None:
    with path.open("w", encoding="utf-8") as fh:
        for case in cases:
            fh.write(json.dumps(case, ensure_ascii=False) + "\n")
    kinds: dict[str, int] = {}
    interventions: dict[str, int] = {}
    for c in cases:
        kinds[c["kind"]] = kinds.get(c["kind"], 0) + 1
        if c["kind"] == "apply":
            key = c["expected"]["intervention"]
            interventions[key] = interventions.get(key, 0) + 1
    print(f"{path.name}: {len(cases)} cases  kinds={kinds}  apply_intervention={interventions}")


